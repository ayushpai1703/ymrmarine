// Points the app at a YSMS server before `cap sync`.
//   YSMS_SERVER_URL=https://<host>/YSMS/index.php node scripts/prepare.js
// Without YSMS_SERVER_URL the server in capacitor.config.json is kept (staging).
// Also writes www/app-config.js so the offline page knows where "Try again" goes.
const fs = require('fs');
const path = require('path');

const cfgPath = path.join(__dirname, '..', 'capacitor.config.json');
const cfg = JSON.parse(fs.readFileSync(cfgPath, 'utf8'));
const wanted = (process.env.YSMS_SERVER_URL || '').trim();
if (wanted) {
  const u = new URL(wanted);
  if (u.protocol !== 'https:') throw new Error('YSMS_SERVER_URL must be https');
  cfg.server.url = u.toString();
  fs.writeFileSync(cfgPath, JSON.stringify(cfg, null, 2) + '\n');
}
const start = cfg.server.url;
fs.writeFileSync(
  path.join(__dirname, '..', 'www', 'app-config.js'),
  '// Generated by scripts/prepare.js\nwindow.YSMS_START_URL = ' + JSON.stringify(start) + ';\n'
);
console.log('YSMS app server: ' + start);
